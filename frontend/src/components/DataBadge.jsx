/** Makes clear whether a value is demo/sample data or from a real source. */
export default function DataBadge({ isSample, verified = false, label }) {
  if (isSample) {
    return <span className="badge badge-sample" title="Demo data, not verified market information">{label || "Sample data"}</span>;
  }
  if (verified) {
    return <span className="badge badge-verified">{label || "Verified source"}</span>;
  }
  return <span className="badge badge-unverified">{label || "Unverified"}</span>;
}

export function AiBadge({ aiGenerated, source }) {
  return aiGenerated ? (
    <span className="badge badge-ai">✨ Generated by Gemini</span>
  ) : (
    <span className="badge badge-rules" title={source === "rules" ? "Produced by a rule-based algorithm" : undefined}>
      ⚙️ Rule-based (not AI)
    </span>
  );
}
